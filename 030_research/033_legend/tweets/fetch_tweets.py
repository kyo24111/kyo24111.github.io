#!/usr/bin/env python3
"""X のタイムラインを fxtwitter API で取り、<handle>_raw.js に書き出す（原文・数字の正本）。

- 和訳・解説・英単語は <handle>_notes.js に id キーで手書きする（こっちは上書きしない）
- 既存の raw とマージするので、古いツイートは消えない（views/likes は最新値で更新）
- リプライは fxtwitter のタイムラインに出ないので対象外

使い方: python3 fetch_tweets.py patrickc [--days 10] [--pages 3]
"""
import argparse, json, os, re, subprocess, time
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
API = 'https://api.fxtwitter.com/2/profile/{h}/statuses'


def get(url):
    # python.org 版 Python は証明書が無いことがあるので curl で取る
    out = subprocess.run(['curl', '-s', '-m', '30', '-A', 'Mozilla/5.0', url],
                         capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def slim(t, handle):
    rp = t.get('reposted_by') or {}
    q = t.get('quote')
    media = [{'type': m.get('type'), 'url': m.get('url'), 'thumb': m.get('thumbnail_url')}
             for m in (t.get('media') or {}).get('all', [])]
    return {
        'id': t['id'], 'url': t['url'], 'ts': t['created_timestamp'],
        'kind': 'repost' if rp.get('screen_name', '').lower() == handle.lower() else ('quote' if q else 'post'),
        'author': t['author']['screen_name'], 'author_name': t['author']['name'],
        'text': t['text'],
        'quote': {'author': q['author']['screen_name'], 'text': q['text'], 'url': q['url']} if q else None,
        'media': media,
        'views': t.get('views'), 'likes': t.get('likes'), 'reposts': t.get('reposts'),
        'replies': t.get('replies'), 'bookmarks': t.get('bookmarks'),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('handle')
    ap.add_argument('--days', type=float, default=10)
    ap.add_argument('--pages', type=int, default=3)
    a = ap.parse_args()
    out = os.path.join(HERE, f'{a.handle}_raw.js')
    old = {}
    if os.path.exists(out):
        m = re.search(r'=\s*(\[.*\]);?\s*$', open(out).read(), re.S)
        old = {t['id']: t for t in json.loads(m.group(1))} if m else {}
    since = time.time() - a.days * 86400
    cursor, got = None, {}
    for _ in range(a.pages):
        d = get(API.format(h=a.handle) + (f'?cursor={cursor}' if cursor else ''))
        rs = d.get('results') or []
        for t in rs:
            if t['created_timestamp'] >= since:
                got[t['id']] = slim(t, a.handle)
        cursor = (d.get('cursor') or {}).get('bottom')
        if not rs or not cursor or min(t['created_timestamp'] for t in rs) < since:
            break
    new = [i for i in got if i not in old]
    old.update(got)
    rows = sorted(old.values(), key=lambda t: -t['ts'])
    stamp = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    with open(out, 'w') as f:
        f.write(f'/* generated by fetch_tweets.py {stamp} — 手で編集しない */\n')
        f.write(f'window.RAW_FETCHED = "{stamp}";\nwindow.RAW_TWEETS = ')
        f.write(json.dumps(rows, ensure_ascii=False, indent=1) + ';\n')
    print(f'{len(rows)} tweets ({len(new)} new) -> {out}')
    for i in new:
        print('  new:', i, got[i]['text'][:70].replace('\n', ' '))


if __name__ == '__main__':
    main()
