#!/usr/bin/env python3
"""deep/<id>.json（日本語のDeep Dive）を news_deep.js にまとめる。
追加・修正したら `python3 build_deep.py` を実行。index.html は DEEP[id] を読む。"""
import json, glob, os
here = os.path.dirname(os.path.abspath(__file__))
out = {}
for p in sorted(glob.glob(os.path.join(here, 'deep', '*.json'))):
    d = json.load(open(p, encoding='utf-8'))
    out[d['id']] = d
js = '/* generated by build_deep.py — 手で編集しない（deep/*.json を直す） */\nvar DEEP = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
open(os.path.join(here, 'news_deep.js'), 'w', encoding='utf-8').write(js)
print(len(out), 'entries ->', 'news_deep.js')
