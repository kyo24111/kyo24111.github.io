/* 小腸: 腹部のなかを蛇行させたコイル */
function _coil() {
  const p = [], N = 52;
  for (let i = 0; i <= N; i++) {
    const t = i / N, ph = t * Math.PI * 8.4;
    const amp = 5.4 + Math.sin(t * Math.PI * 2.2) * 1.5;
    const dep = 2.0 + Math.sin(t * Math.PI * 3.1) * 0.9;
    p.push([Math.sin(ph) * amp, 111 - t * 14 + Math.sin(ph * 2) * 0.6, 2.0 + Math.cos(ph) * dep]);
  }
  return [{ t:'l', p, up:[0,1,0], nv:190, nu:12, tension:0.5,
            r:[[0,1.15,1.15],[.5,1.45,1.45],[1,1.1,1.1]] }];
}

