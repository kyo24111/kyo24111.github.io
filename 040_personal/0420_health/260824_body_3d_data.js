/* x を反転した複製を足す（輪郭の四肢用） */
function _mirX(b) {
  const c = JSON.parse(JSON.stringify(b));
  const neg = (v) => { v[0] = -v[0]; return v; };
  if (c.p) Array.isArray(c.p[0]) ? c.p.forEach(neg) : neg(c.p);
  if (c.a) neg(c.a); if (c.b && Array.isArray(c.b)) neg(c.b);
  if (c.q) { c.q[1] = -(c.q[1] || 0); c.q[2] = -(c.q[2] || 0); }
  return [b, c];
}

